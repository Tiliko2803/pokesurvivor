#!/usr/bin/env python3
"""Generate offline learnsets for Coberturas from a pinned PokéAPI snapshot.

Run: python tools/build_coverage.py
Only normal level-up, egg, tutor and machine learning in main-series version
 groups is accepted. No inference from types, evolution relatives or other forms.
"""
import concurrent.futures
import csv
import hashlib
import io
import json
from pathlib import Path
import subprocess
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SOURCE_SHA = '6fd69dfe90465ba96534f6816fc817737d1f97f6'
SOURCE_URL = f'https://github.com/PokeAPI/pokeapi/tree/{SOURCE_SHA}/data/v2/csv'
CACHE = ROOT / 'tools' / 'cache' / 'coverage' / SOURCE_SHA
FILES = ['moves.csv', 'pokemon.csv', 'pokemon_moves.csv', 'pokemon_move_methods.csv', 'version_groups.csv']
METHODS = {'level-up', 'egg', 'tutor', 'machine'}
EXCLUDED_GAMES = {'colosseum', 'xd', 'champions'}
# Learning the final move unlocks its playable base branch (Powder Snow -> Blizzard).
# Kept explicit; unrelated same-type attacks never grant compatibility.
FAMILY_ALIASES = {'powder-snow': ['blizzard']}
# Explicit game-design lists for gift characters, never PokéAPI form IDs 10001/10002.
CUSTOM = {
    '10001': ['thunderbolt', 'rock-slide', 'confusion'],
    '10002': ['aerial-ace', 'psycho-cut', 'rock-slide', 'bite'],
}


def download(name):
    path = CACHE / name
    if not path.exists():
        url = f'https://raw.githubusercontent.com/PokeAPI/pokeapi/{SOURCE_SHA}/data/v2/csv/{name}'
        with urllib.request.urlopen(url, timeout=45) as response:
            data = response.read()
        # Validate before caching: error HTML must never become a compatibility table.
        if not data.startswith(b'id,') and not data.startswith(b'pokemon_id,'):
            raise ValueError(f'Unexpected CSV header for {name}')
        path.write_bytes(data)
    return name, path.read_bytes()


def build():
    CACHE.mkdir(parents=True, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=5) as executor:
        raw = dict(executor.map(download, FILES))
    tables = {name: list(csv.DictReader(io.StringIO(data.decode('utf-8')))) for name, data in raw.items()}
    # Read the actual game catalog, not a hand-maintained duplicate of its move IDs.
    script = """
const fs=require('node:fs'),vm=require('node:vm'),G={};
const ctx=vm.createContext({G,window:{G}});
for(const f of ['js/core/util.js','js/data/pokedex.js','js/data/moves.js'])vm.runInContext(fs.readFileSync(f,'utf8'),ctx);
console.log(JSON.stringify({mons:G.DEX,moves:G.Moves.ALL.map(m=>m.id),pool:G.Moves.POOL}));
"""
    catalog = json.loads(subprocess.check_output(['node', '-e', script], cwd=ROOT, text=True))
    move_ids = {m['identifier']: int(m['id']) for m in tables['moves.csv']}
    missing = set(catalog['moves']) - move_ids.keys()
    if missing:
        raise ValueError(f'Game moves missing from PokéAPI: {missing}')
    moves = catalog['moves']
    index_by_id = {move_ids[name]: i for i, name in enumerate(moves)}
    for root, aliases in FAMILY_ALIASES.items():
        for name in aliases:
            if name not in move_ids or root not in moves:
                raise ValueError(f'Unknown coverage family: {root} / {name}')
            index_by_id[move_ids[name]] = moves.index(root)
    mons = {int(mon['dex']): mon for mon in catalog['mons']}
    pokemon = {int(p['id']): p for p in tables['pokemon.csv']}
    for dex in mons:
        if dex > 1025 or dex not in pokemon or pokemon[dex]['is_default'] != '1':
            raise ValueError(f'Unmapped species/form: {dex}')
    method_ids = {int(row['id']) for row in tables['pokemon_move_methods.csv'] if row['identifier'] in METHODS}
    version_ids = {int(row['id']) for row in tables['version_groups.csv'] if row['identifier'] not in EXCLUDED_GAMES}
    learnsets = {dex: set() for dex in mons}
    for row in tables['pokemon_moves.csv']:
        dex, move = int(row['pokemon_id']), int(row['move_id'])
        if dex in learnsets and move in index_by_id and int(row['pokemon_move_method_id']) in method_ids and int(row['version_group_id']) in version_ids:
            learnsets[dex].add(index_by_id[move])
    result = {
        'source': SOURCE_URL,
        'commit': SOURCE_SHA,
        'methods': sorted(METHODS),
        'excludedGames': sorted(EXCLUDED_GAMES),
        'sha256': {name: hashlib.sha256(data).hexdigest() for name, data in raw.items()},
        'moves': moves,
        'families': FAMILY_ALIASES,
        'learnsets': {str(dex): sorted(ids) for dex, ids in sorted(learnsets.items())},
        'custom': CUSTOM,
    }
    header = '/* Generated by tools/build_coverage.py from PokéAPI. Read docs/coverage.md. */\n'
    out = ROOT / 'js/data/coverage-data.js'
    out.write_text(header + 'G.CoverageData = ' + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ';\n')
    coverage = {}
    for dex, mon in mons.items():
        base = set(catalog['pool']['normal'])
        for kind in mon['types']:
            base.update(catalog['pool'].get(kind, []))
        coverage[dex] = [moves[i] for i in sorted(learnsets[dex]) if moves[i] not in base]
    summary = {'pokemon': len(mons), 'withCoverage': sum(bool(v) for v in coverage.values()),
               'withoutCoverage': [dex for dex, v in coverage.items() if not v], 'bytes': out.stat().st_size,
               'examples': {str(dex): coverage[dex] for dex in [3, 25, 129, 202, 257, 260, 493, 638] if dex in coverage}}
    (CACHE / 'summary.json').write_text(json.dumps(summary, indent=2))
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == '__main__':
    build()
