/* Generate the existing development URL from current sources. Never generates index.html. */
const fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..');
let html = fs.readFileSync(path.join(root, 'dev.html'), 'utf8')
  .replace('<head>', '<head>\n<base href="../">')
  .replace(/<title>.*?<\/title>/, '<title>PokéSurvivor · Boss Rush · Groudon</title>')
  .replace(/<!-- seo:begin -->[\s\S]*?<!-- seo:end -->/g, '')
  .replace(/<script defer src="js\/core\/firebase-config\.js"><\/script>/,
    '<script>window.G = window.G || {}; G.FIREBASE_CONFIG = null;</script>')
  .replace(/<script defer src="js\/main\.js"><\/script>/,
    '<script defer src="dev/boss-rush-rules.js"></script>\n<script defer src="dev/groudon.js"></script>\n<script defer src="dev/boss-rush-preview.js"></script>\n<script defer src="dev/boss-rush-boot.js"></script>')
  .replace('</head>', '<link rel="stylesheet" href="dev/boss-rush.css">\n</head>');
html = html.replace('<!-- dev.html: página fuente. Aquí se edita; index.html lo genera tools/build.js. -->',
  '<!-- Generated by tools/build-boss-rush-preview.cjs from dev.html; isolated Groudon preview. -->');
fs.writeFileSync(path.join(root, 'dev/index.html'), html);
console.log('Generated dev/index.html · Boss Rush Groudon preview');
