/* Generate the existing development URL from current sources. Never generates index.html. */
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const root = path.join(__dirname, '..');
let html = fs.readFileSync(path.join(root, 'dev.html'), 'utf8')
  .replace('<head>', '<head>\n<base href="../">')
  .replace(/<title>.*?<\/title>/, '<title>PokéSurvivor · Boss Rush · Hoenn</title>')
  .replace(/<!-- seo:begin -->[\s\S]*?<!-- seo:end -->/g, '')
  .replace(/<script defer src="js\/core\/firebase-config\.js"><\/script>/,
    '<script>window.G = window.G || {}; G.FIREBASE_CONFIG = null;</script>')
  .replace('<script defer src="js/systems/boss-rush.js"></script>', '<script defer src="dev/tyranitar.js"></script>\n<script defer src="dev/boss-rush-preview.js"></script>')
  .replace('<script defer src="js/main.js"></script>', '<script defer src="dev/boss-rush-boot.js"></script>');
html = html.replace('<!-- dev.html: página fuente. Aquí se edita; index.html lo genera tools/build.js. -->',
  '<!-- Generated by tools/build-boss-rush-preview.cjs from dev.html; isolated Hoenn preview. -->');
const scripts = [...html.matchAll(/<script[^>]*src="([^"?]+)(?:\?[^"]*)?"/g)].map(m => m[1]);
const version = crypto.createHash('sha1').update(html + scripts.map(p => fs.readFileSync(path.join(root, p),'utf8')).join('\n') +
  fs.readFileSync(path.join(root,'dev/boss-rush.css'),'utf8')).digest('hex').slice(0,10);
html = html.replace(/(<script[^>]*src="[^"?]+)(?:\?[^"]*)?"/g, `$1?v=bossrush-${version}"`)
  .replace(/(<link[^>]*href="(?:css\/style|dev\/boss-rush)\.css)(?:\?[^"]*)?"/g, `$1?v=bossrush-${version}"`)
  .replace('<meta charset="utf-8">', `<meta charset="utf-8">\n<meta name="ps-preview-version" content="${version}">`);
fs.writeFileSync(path.join(root, 'dev/index.html'), html);
console.log('Generated dev/index.html · Boss Rush Hoenn preview · ' + version);
